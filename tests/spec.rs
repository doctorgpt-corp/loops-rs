//! The shipped OpenAPI spec, the generated client and the route table agree.

use std::collections::BTreeSet;
use std::path::Path;

use loops_so::routes::Route;
use loops_so::{LOOPS_API_VERSION, OPENAPI_SPEC, openapi_spec_path};
use serde_json::Value;

const HTTP_METHODS: [&str; 8] = [
    "get", "put", "post", "delete", "patch", "head", "options", "trace",
];

fn spec() -> Value {
    serde_yaml_ng::from_str(OPENAPI_SPEC).expect("the shipped spec is valid YAML")
}

fn manifest_file(relative: &str) -> String {
    std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(relative))
        .unwrap_or_else(|err| panic!("reading {relative}: {err}"))
}

/// `/v1/campaigns/{campaignId}` and `/v1/campaigns/{id}` both become
/// `/v1/campaigns/{}`.
fn normalise(path: &str) -> String {
    path.split('/')
        .map(|segment| {
            if segment.starts_with('{') {
                "{}"
            } else {
                segment
            }
        })
        .collect::<Vec<_>>()
        .join("/")
}

/// Every `(METHOD, path)` operation under `paths` in the shipped spec.
fn spec_operations() -> BTreeSet<(String, String)> {
    let spec = spec();
    spec["paths"]
        .as_object()
        .expect("spec has paths")
        .iter()
        .flat_map(|(path, item)| {
            item.as_object()
                .into_iter()
                .flat_map(|methods| methods.keys())
                .filter(|method| HTTP_METHODS.contains(&method.as_str()))
                .map(move |method| (method.to_uppercase(), normalise(path)))
        })
        .collect()
}

/// Every `(METHOD, path)` the generated client documents with a
/// ``/// * Path: `GET /v1/...` `` line.
fn generated_operations() -> Vec<(String, String)> {
    manifest_file("src/generated/client.rs")
        .lines()
        .filter_map(|line| line.trim().strip_prefix("/// * Path: `"))
        .map(|rest| {
            let rest = rest.trim_end_matches('`');
            let (method, path) = rest.split_once(' ').expect("`METHOD path`");
            (method.to_owned(), normalise(path))
        })
        .collect()
}

#[test]
fn spec_path_is_a_file_with_the_embedded_contents() {
    let path = openapi_spec_path();
    assert!(path.is_file(), "{}", path.display());
    assert_eq!(std::fs::read_to_string(path).unwrap(), OPENAPI_SPEC);
}

#[test]
fn spec_is_an_openapi_document() {
    let spec = spec();
    assert!(spec["openapi"].as_str().unwrap().starts_with("3."));
    assert!(!spec["paths"].as_object().unwrap().is_empty());
}

#[test]
fn api_version_constant_matches_the_spec() {
    assert_eq!(spec()["info"]["version"].as_str(), Some(LOOPS_API_VERSION));
}

#[test]
fn spec_lists_every_operation_the_generated_client_calls() {
    let generated = generated_operations();
    let spec = spec_operations();
    let generated_set: BTreeSet<_> = generated.iter().cloned().collect();
    assert_eq!(
        generated.len(),
        generated_set.len(),
        "duplicate generated operations"
    );
    let unknown: Vec<_> = generated_set.difference(&spec).collect();
    assert!(
        unknown.is_empty(),
        "generated operations missing from the spec: {unknown:?}"
    );
    let dropped: Vec<_> = spec.difference(&generated_set).collect();
    assert!(
        dropped.is_empty(),
        "spec operations the generator dropped: {dropped:?}"
    );
}

#[test]
fn every_route_is_a_spec_operation() {
    let spec = spec_operations();
    for route in Route::ALL {
        let operation = (route.method().as_str().to_owned(), normalise(route.path()));
        assert!(
            spec.contains(&operation),
            "{route:?} ({operation:?}) is not in the spec"
        );
    }
}

#[test]
fn every_spec_operation_has_a_route() {
    let routes: BTreeSet<_> = Route::ALL
        .iter()
        .map(|route| (route.method().as_str().to_owned(), normalise(route.path())))
        .collect();
    let unwrapped: Vec<_> = spec_operations()
        .into_iter()
        .filter(|op| !routes.contains(op))
        .collect();
    assert!(
        unwrapped.is_empty(),
        "spec operations without a LoopsClient method and Route: {unwrapped:?}. \
         Add the method, the route, its mock fixture and tests together."
    );
}

#[test]
fn generator_versions_agree() {
    let header = manifest_file("src/generated/mod.rs");
    let generated_by = header
        .lines()
        .find_map(|line| line.strip_prefix("//! Generated by `oas3-gen v"))
        .and_then(|rest| rest.strip_suffix('`'))
        .expect("generated header names the oas3-gen version");

    let manifest = manifest_file("Cargo.toml");
    let support_pin = manifest
        .lines()
        .find_map(|line| line.strip_prefix("oas3-gen-support = \"="))
        .and_then(|rest| rest.strip_suffix('"'))
        .expect("Cargo.toml pins oas3-gen-support exactly");

    let justfile = manifest_file("justfile");
    let just_pin = justfile
        .lines()
        .find_map(|line| line.strip_prefix("oas3_gen_version := \""))
        .and_then(|rest| rest.strip_suffix('"'))
        .expect("justfile sets oas3_gen_version");

    assert_eq!(generated_by, support_pin, "src/generated/ vs Cargo.toml");
    assert_eq!(generated_by, just_pin, "src/generated/ vs justfile");
}

/// Tripwire for an oas3-gen limitation documented on `loops_so::generated`:
/// a decoded discriminated-union member loses its tag when re-serialized.
/// When this fails, the generator has been fixed: drop the caveat from the
/// `generated` module docs and CLAUDE.md, then delete this test.
#[test]
fn decoded_union_members_still_drop_their_tag_on_reserialize() {
    let node: loops_so::generated::SimplifiedWorkflowNode =
        serde_json::from_value(serde_json::json!({ "typeName": "ExitAction", "nextNodeIds": [] }))
            .unwrap();
    assert!(matches!(
        node,
        loops_so::generated::SimplifiedWorkflowNode::ExitAction(_)
    ));
    let reserialized = serde_json::to_value(&node).unwrap();
    assert!(reserialized.get("typeName").is_none(), "{reserialized}");
}
